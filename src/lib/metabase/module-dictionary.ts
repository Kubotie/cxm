const BY_ID = new Map(MODULE_DICTIONARY.map(m => [m.id, m]));

export function moduleDef(id: string): ModuleDefinition | null {
  return BY_ID.get(id) ?? null;
}

/** 指標に使ってよいモジュールか。辞書に無いものは false */
export function isCountable(id: string): boolean {
  return BY_ID.get(id)?.includeInApp === true;
}

